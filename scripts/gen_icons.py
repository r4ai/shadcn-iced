#!/usr/bin/env python3
"""Generate `crates/shadcn_iced_core/src/icon/lucide.rs` from lucide-static's
`font/codepoints.json`.

Usage: uv run --project scripts scripts/gen_icons.py <path-to-lucide-static-package>
"""
import json
import sys
from pathlib import Path

RESERVED = {"type", "box", "move", "ref", "use", "loop", "match", "crate", "self", "super"}


def main():
    pkg = Path(sys.argv[1])
    codepoints = json.loads((pkg / "font/codepoints.json").read_text())
    version = json.loads((pkg / "package.json").read_text())["version"]
    out = [
        f"//! Every [Lucide](https://lucide.dev) icon (lucide-static {version}) as a",
        "//! codepoint of the bundled `lucide.ttf` font.",
        "//!",
        "//! Generated by `scripts/gen_icons.py`; do not edit by hand.",
        "",
        "use super::Icon;",
        "",
    ]
    names = []
    for name, cp in sorted(codepoints.items()):
        ident = name.replace("-", "_").upper()
        names.append((name, ident))
        out.append(f"/// The `{name}` icon.")
        out.append(f"pub const {ident}: Icon = Icon::new('\\u{{{cp:x}}}');")
    out.append("")
    out.append("/// Every icon as `(kebab-case name, icon)`, sorted by name.")
    out.append("pub const ALL: &[(&str, Icon)] = &[")
    for name, ident in names:
        out.append(f'    ("{name}", {ident}),')
    out.append("];")
    dest = Path(__file__).resolve().parent.parent / "crates/shadcn_iced_core/src/icon/lucide.rs"
    dest.parent.mkdir(parents=True, exist_ok=True)
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest} ({len(names)} icons)")


if __name__ == "__main__":
    main()
